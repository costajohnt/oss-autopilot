import { describe, it, expect } from 'vitest';
import { classifyCloseReason, classifySelfClose, type CloseContext } from './close-reason.js';

const ctx = (closer: string | undefined, ...comments: Array<[string, string, boolean?]>): CloseContext => ({
  author: 'me',
  closer,
  comments: comments.map(([author, body, isBot]) => ({ author, body, isBot })),
});

describe('classifyCloseReason (#1824)', () => {
  it.each([
    [ctx('maint', ['maint', 'We do not accept AI-generated PRs, see our AI policy.']), 'ai-policy'],
    [ctx('maint', ['maint', 'This looks like it was generated by an LLM.']), 'ai-policy'],
    [ctx('me', ['maint', 'Closing as duplicate of #12']), 'superseded'],
    [ctx('maint', ['maint', 'This was already fixed in main.']), 'superseded'],
    [ctx('maint', ['maint', 'Superseded by #40, thanks!']), 'superseded'],
    [{ ...ctx('github-actions'), closerIsBot: true }, 'stale'],
    [ctx('maint', ['maint', 'Closing due to inactivity.']), 'stale'],
    [ctx('me'), 'self-closed'],
    [ctx('maint', ['maint', 'Not the direction we want, thanks.']), 'rejected'],
    [ctx(undefined), 'unknown'],
  ])('%#: classifies as %s', (input, expected) => {
    expect(classifyCloseReason(input)).toBe(expected);
  });

  // False positives seen on real closed PRs.
  it.each([
    [
      'review bot summary',
      ctx('me', ['coderabbitai', 'auto-generated comment: summarize by coderabbit.ai', true]),
      'self-closed',
    ],
    [
      'bot template mentions duplicates',
      ctx('maint', ['bot', 'this PR may be closed as a duplicate', true]),
      'rejected',
    ],
    ['maintainer mentions a tool', ctx('maint', ['maint', 'Should not be hard with Claude']), 'rejected'],
    ['technical "stale"', ctx('maint', ['maint', 'This does not fix the stale-line bug.']), 'rejected'],
    ['sonar metric', ctx('maint', ['maint', 'new_duplicated_lines_density is 0']), 'rejected'],
    ['author mentions AI', ctx('maint', ['me', 'AI-generated draft, reviewed by me']), 'rejected'],
  ])('%s does not count', (_label, input, expected) => {
    expect(classifyCloseReason(input)).toBe(expected);
  });
});

describe('classifySelfClose (#1824)', () => {
  const self = (...comments: Array<[string, string, boolean?]>): CloseContext => ({
    author: 'me',
    closer: 'me',
    comments: comments.map(([author, body, isBot]) => ({ author, body, isBot })),
  });

  // Phrasings taken from real author closing comments.
  it.each([
    ['Closing since v0.6.12 covers this (dbe720e). Thanks for the fix!', 'superseded'],
    ['Closing, #1684 landed the same fix.', 'superseded'],
    ['#1408 is in and covers everything here, so closing this one.', 'superseded'],
    ['Closing in favor of #6087, which takes a different angle.', 'superseded'],
    ['Closing this PR, the fix was already applied upstream in commit a1ad602.', 'superseded'],
    ["Closing this to keep the queue tidy since it hasn't gotten traction.", 'no-traction'],
    ["Closing this since the repo doesn't seem to be actively reviewing PRs.", 'no-traction'],
    ["Closing this since it's been quiet for a while.", 'no-traction'],
  ])('%j is %s', (body, expected) => {
    expect(classifySelfClose(self(['me', body]))).toBe(expected);
  });

  it('falls back to whether anyone human engaged before the close', () => {
    expect(classifySelfClose(self(['maint', 'Not sure this is the right direction'], ['me', 'Fair, closing']))).toBe(
      'after-feedback',
    );
    expect(classifySelfClose(self(['coderabbitai', 'auto-generated summary', true]))).toBe('no-response');
    expect(classifySelfClose(self())).toBe('no-response');
  });
});
