import { describe, it, expect } from 'vitest';
import { validateMessage } from './validation.js';

// Audit L1 regex: legitimate maintainer-facing text must pass, real
// attribution shapes (trailers, footers, zero-width tricks) must not.
describe('validateMessage AI-attribution filter (L1) adversarial', () => {
  it.each([
    'Dropped the "Co-Authored-By: Claude" trailer from the commit as you asked.',
    'Fixed the 🤖 bot label rendering in the PR list (the emoji was double-width).',
    'The fixtures were generated with claude-cli v0.3 (the repo tool), not an LLM.',
  ])('accepts legitimate content: %s', (msg) => {
    expect(() => validateMessage(msg)).not.toThrow();
  });

  it.each([
    'Thanks!\n\nClaude-Session: https://claude.ai/code/session_01ABC',
    'Generated by Claude Code',
    'Made with Claude Code',
    'Co-authored-by: Claude <noreply@anthropic.com>'.replace('Claude', 'C\u200Blaude'), // zero-width space
  ])('rejects real attribution: %s', (msg) => {
    expect(() => validateMessage(msg)).toThrow(/attribution/);
  });
});
